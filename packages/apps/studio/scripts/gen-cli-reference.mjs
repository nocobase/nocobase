// Generates the command reference of Studio's CLI, `docs/cli/reference/`, from the commands its API document gives
// the CLI: every operation's `x-cli` extension, or its tag, path and method, with Studio's exclusions applied. One file
// per area (a command's first word) and an index. Each command says how it is typed, its arguments and flags, what it
// answers, who may run it and the business action it needs, the request it makes, and its examples.
//
// Studio starts through the framework's `inspectApplication` (`vendor/nocobase3/scripts/check-openapi.mjs`: SQLite test
// databases, in a child process), so the reference is what the current sources serve, not a copy someone keeps by hand.
//
// Usage:
//   node scripts/gen-cli-reference.mjs           # write the reference
//   node scripts/gen-cli-reference.mjs --check   # fail when it is not what the sources would write (CI)
import { mkdir, readdir, readFile, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';

import * as prettier from 'prettier';

import { studioTarget } from './check-openapi.mjs';
import { inspectApplication } from '../../../../scripts/check-openapi.mjs';

const repositoryRoot = path.resolve(
  fileURLToPath(new URL('..', import.meta.url)),
);
export const referenceDir = path.join(repositoryRoot, 'docs/cli/reference');

const GENERATED =
  '<!-- Generated by scripts/gen-cli-reference.mjs from the API document. Do not edit: change the route’s describeRoute() or x-cli, then run `node scripts/gen-cli-reference.mjs`. -->';

const words = (command) => command.id.split(':').join(' ');

/** Text for a Markdown table cell: one line, pipes escaped. */
const cell = (text) =>
  String(text ?? '')
    .replace(/\s+/gu, ' ')
    .replaceAll('|', '\\|')
    .trim();

/** The request path without the application's base path: `/main/api/x` is `/api/x`. */
const requestPath = (command) => command.path.replace(/^.*?(?=\/api\/)/u, '');

function positionalOf(command) {
  return command.parameters
    .filter((parameter) => parameter.position !== undefined)
    .sort((a, b) => a.position - b.position);
}

/** A command as typed: its words, its arguments, and its required flags. */
export function usageOf(command, bin) {
  const parts = [bin, words(command)];
  for (const parameter of positionalOf(command))
    parts.push(
      parameter.required ? `<${parameter.name}>` : `[<${parameter.name}>]`,
    );
  for (const parameter of command.parameters) {
    if (parameter.position !== undefined || !parameter.required) continue;
    if (parameter.default !== undefined || parameter.env?.length) continue;
    parts.push(
      parameter.type === 'boolean'
        ? `--${parameter.name}`
        : `--${parameter.name} <${parameter.in === 'file' || parameter.binary ? 'path' : parameter.type}>`,
    );
  }
  // A body that only a file can give: no flag fills any of its fields.
  if (
    command.body?.file &&
    command.body.required &&
    !command.parameters.some((parameter) => parameter.in === 'body')
  )
    parts.push(`--${command.body.file} <file.json>`);
  return parts.join(' ');
}

function typeOf(parameter) {
  if (parameter.in === 'file' || parameter.binary)
    return parameter.changed ? 'boolean' : 'path';
  if (parameter.enum?.length) return parameter.enum.join(' \\| ');
  return parameter.type;
}

function notesOf(parameter) {
  return [
    parameter.required ? 'required' : '',
    parameter.default !== undefined
      ? `default ${JSON.stringify(parameter.default)}`
      : '',
    parameter.env?.length
      ? `default from ${parameter.env
          .map((source) =>
            typeof source === 'string'
              ? `$${source}`
              : `${source.path} of $${source.file}`,
          )
          .join(' or ')}`
      : '',
    parameter.alias ? `alias -${parameter.alias}` : '',
    parameter.contentFile ? `or --${parameter.name}-file <path>` : '',
    parameter.upload
      ? `uploaded first${parameter.upload.multiple ? ', repeatable' : ''}`
      : '',
    parameter.ticket
      ? `streamed to an upload ticket, at most ${parameter.ticket.maxBytes} bytes`
      : '',
    parameter.changed
      ? `sends the files changed in ${parameter.changed.dir}`
      : '',
    (parameter.type === 'string[]' || parameter.type === 'number[]') &&
    !parameter.upload
      ? 'repeatable'
      : '',
  ].filter(Boolean);
}

function outputOf(command) {
  switch (command.output.kind) {
    case 'list':
      return `A list${command.output.columns?.length ? ` (table columns: ${command.output.columns.map((column) => `\`${column}\``).join(', ')})` : ''}; with \`--json\`, \`result.data\` is the array and \`result.meta\` the paging.`;
    case 'download':
      return 'A file, saved in the current directory under its own name or where `--out` says; with `--json`, `result.data` says where it went.';
    case 'empty':
      return 'Nothing; prints `Done.`.';
    default:
      return 'One record, field by field; with `--json`, `result.data`.';
  }
}

function whoOf(command) {
  const run = command.identities.includes('run');
  const person = command.identities.includes('person');
  const who =
    run && person
      ? 'People, and agents in a run'
      : run
        ? 'Only agents in a run'
        : 'People (a sign-in or an API key)';
  return command.action
    ? `${who}; needs the action \`${command.action}\`.`
    : `${who}.`;
}

/** One command's section. */
export function commandSection(command, bin) {
  const lines = [`## ${words(command)}`, '', command.summary, ''];
  if (command.description) lines.push(command.description, '');
  lines.push('```bash', usageOf(command, bin), '```', '');
  const positional = positionalOf(command);
  if (positional.length > 0) {
    lines.push('| Argument | Description |', '| --- | --- |');
    for (const parameter of positional)
      lines.push(
        `| \`${parameter.name}\` | ${cell([parameter.description ?? '', parameter.required ? '' : '(optional)'].filter(Boolean).join(' '))} |`,
      );
    lines.push('');
  }
  const flags = command.parameters.filter(
    (parameter) => parameter.position === undefined,
  );
  const extra = [
    ...(command.body?.file
      ? [
          [
            `--${command.body.file}`,
            'path',
            'The request body as a JSON object; the flags override its fields.',
          ],
        ]
      : []),
    ...(command.output.kind === 'download'
      ? [
          [
            '--out',
            'path',
            'Where to save the file, or a directory to save it in.',
          ],
        ]
      : []),
    ...(command.confirm
      ? [['--yes', 'boolean', `Go ahead without asking “${command.confirm}”`]]
      : []),
  ];
  if (flags.length > 0 || extra.length > 0) {
    lines.push('| Flag | Type | Description |', '| --- | --- | --- |');
    for (const parameter of flags) {
      const notes = notesOf(parameter);
      lines.push(
        `| \`--${parameter.name}\` | ${cell(typeOf(parameter))} | ${cell([parameter.description ?? '', notes.length ? `(${notes.join('; ')})` : ''].filter(Boolean).join(' '))} |`,
      );
    }
    for (const [flag, type, description] of extra)
      lines.push(`| \`${flag}\` | ${type} | ${cell(description)} |`);
    lines.push('');
  }
  lines.push(
    `**Output:** ${outputOf(command)}`,
    '',
    `**Who:** ${whoOf(command)}`,
    '',
    `**Request:** \`${command.method} ${requestPath(command)}\`${command.operationId ? ` (\`${command.operationId}\`)` : ''}`,
    '',
  );
  if (command.examples?.length) {
    lines.push('**Examples:**', '', '```bash');
    for (const example of command.examples) lines.push(`${bin} ${example}`);
    lines.push('```', '');
  }
  return lines.join('\n');
}

/** The reference's files by name: `index.md` and one per area, before formatting. */
export function renderReference(
  commands,
  { bin = 'nb-studio', title = 'NocoBase Studio' } = {},
) {
  const areas = new Map();
  for (const command of [...commands].sort((a, b) =>
    a.id.localeCompare(b.id),
  )) {
    const area = command.id.split(':')[0];
    areas.set(area, [...(areas.get(area) ?? []), command]);
  }
  const files = new Map();
  const index = [
    `# ${title} CLI command reference`,
    '',
    GENERATED,
    '',
    `Every command is one API route. \`${bin} <command> --help\` and \`${bin} docs <command>\` show the same on the command line, for the commands you may run; this reference lists every command, with who may run it. The guides beside this directory explain signing in, profiles, CI and agents: start with [getting started](../getting-started.md).`,
    '',
    '| Area | Commands |',
    '| --- | --- |',
  ];
  for (const [area, list] of areas) {
    index.push(
      `| [${area}](${area}.md) | ${cell(list.map((command) => `\`${words(command)}\``).join(', '))} |`,
    );
    files.set(
      `${area}.md`,
      [
        `# ${bin} ${area}`,
        '',
        GENERATED,
        '',
        ...list.map((command) => commandSection(command, bin)),
      ].join('\n'),
    );
  }
  files.set('index.md', `${index.join('\n')}\n`);
  return files;
}

async function formatted(files) {
  const options =
    (await prettier.resolveConfig(path.join(referenceDir, 'index.md'))) ?? {};
  const result = new Map();
  for (const [name, content] of files)
    result.set(
      name,
      await prettier.format(content, {
        ...options,
        filepath: path.join(referenceDir, name),
      }),
    );
  return result;
}

async function main(argv) {
  const check = argv.includes('--check');
  const inspection = await inspectApplication(studioTarget);
  const description = inspection.cliDescription ?? {};
  const files = await formatted(
    renderReference(inspection.cliCommands ?? [], {
      bin: description.bin ?? 'nb-studio',
      title: description.title ?? 'NocoBase Studio',
    }),
  );
  const existing = new Set(
    (await readdir(referenceDir).catch(() => [])).filter((name) =>
      name.endsWith('.md'),
    ),
  );
  if (check) {
    const stale = [];
    for (const [name, content] of files) {
      const current = await readFile(
        path.join(referenceDir, name),
        'utf8',
      ).catch(() => undefined);
      if (current !== content) stale.push(name);
      existing.delete(name);
    }
    stale.push(...[...existing].map((name) => `${name} (no longer generated)`));
    if (stale.length === 0) {
      console.log(`The CLI reference is up to date (${files.size} files).`);
      return 0;
    }
    console.error(
      `The CLI reference in ${path.relative(repositoryRoot, referenceDir)} is not what the API document gives:\n${stale.map((name) => `  ${name}`).join('\n')}\nRun \`node scripts/gen-cli-reference.mjs\` and commit the result.`,
    );
    return 1;
  }
  await mkdir(referenceDir, { recursive: true });
  for (const name of existing)
    if (!files.has(name)) await rm(path.join(referenceDir, name));
  for (const [name, content] of files)
    await writeFile(path.join(referenceDir, name), content);
  console.log(
    `Wrote ${files.size} files to ${path.relative(repositoryRoot, referenceDir)}.`,
  );
  return 0;
}

if (
  process.argv[1] &&
  path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  process.exitCode = await main(process.argv.slice(2));
}
