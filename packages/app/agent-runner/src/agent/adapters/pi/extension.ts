/**
 * The runner permission bridge: a Pi extension the adapter loads with
 * `--extension` so the runner's policy decides every tool call.
 *
 * Pi has no approval prompt of its own (its docs: "it does not ask for
 * approval before every tool call"). Its extension API is the hook: a
 * `tool_call` handler runs before every tool executes, including calls a tool
 * such as `codemode` makes, and can block it with a reason the model reads as
 * the tool's error result. The handler asks the adapter over Pi's RPC
 * extension UI subprotocol: an `input` dialog whose title is
 * {@link PERMISSION_DIALOG_TITLE} and whose placeholder is the JSON call
 * description; the adapter answers with the JSON decision. Anything other
 * than an explicit allow blocks the call (fail closed).
 *
 * The extension also registers {@link PERMISSION_COMMAND}, so the adapter can
 * confirm through `get_commands` that the bridge loaded before it prompts.
 *
 * The source is plain JavaScript in a `.ts` file (Pi loads extensions through
 * jiti) and imports nothing, so it runs with whatever Pi version is installed.
 */

export const PERMISSION_DIALOG_TITLE = 'nocobase-runner-permission/v1';
export const PERMISSION_COMMAND = 'nocobase-runner-permission';
export const PERMISSION_EXTENSION_FILE = 'nocobase-runner-permission.ts';

/** What the extension sends for one tool call. */
export interface PermissionRequest {
  toolCallId: string;
  parentToolCallId?: string;
  toolName: string;
  input: Record<string, unknown>;
}

/** What the adapter answers. */
export interface PermissionAnswer {
  allow: boolean;
  /** Read by the model when the call is blocked. */
  message?: string;
}

export function parsePermissionRequest(
  placeholder: unknown,
): PermissionRequest | undefined {
  if (typeof placeholder !== 'string') return undefined;
  try {
    const value = JSON.parse(placeholder) as Partial<PermissionRequest>;
    if (typeof value.toolName !== 'string') return undefined;
    return {
      toolCallId: typeof value.toolCallId === 'string' ? value.toolCallId : '',
      ...(typeof value.parentToolCallId === 'string'
        ? { parentToolCallId: value.parentToolCallId }
        : {}),
      toolName: value.toolName,
      input: value.input && typeof value.input === 'object' ? value.input : {},
    };
  } catch {
    return undefined;
  }
}

export const PERMISSION_EXTENSION_SOURCE: string = `// Generated by the runner for this run; deleted when the run ends.
const TITLE = ${JSON.stringify(PERMISSION_DIALOG_TITLE)};
const DENIED = "The runner policy denied this tool call.";

export default function runnerPermission(pi) {
  pi.registerCommand(${JSON.stringify(PERMISSION_COMMAND)}, {
    description: "Runner permission bridge (no-op)",
    handler: async () => {},
  });

  pi.on("tool_call", async (event, ctx) => {
    let answer;
    try {
      const request = JSON.stringify({
        toolCallId: event.toolCallId,
        parentToolCallId: event.parentToolCallId,
        toolName: event.toolName,
        input: event.input,
      });
      answer = await ctx.ui.input(TITLE, request, ctx.signal ? { signal: ctx.signal } : undefined);
    } catch (error) {
      return { block: true, reason: DENIED + " (permission check failed: " + String(error && error.message || error) + ")" };
    }
    let decision;
    try {
      decision = JSON.parse(answer === undefined ? "" : answer);
    } catch {
      decision = undefined;
    }
    if (decision && decision.allow === true) return undefined;
    return {
      block: true,
      reason: decision && typeof decision.message === "string" ? decision.message : DENIED,
    };
  });
}
`;
