// Generates the catalog of the NocoBase UI Library that applications receive with the nocobase-app-development Skill,
// `references/frontend/references/ui-library.md`, from the registry sources in `ui-library/`: every item's kind, install
// command and location, description, wiring notes, plugin dependencies and example. It is what an agent reads when the
// shadcn MCP server and `shadcn search @nocobase` cannot reach https://ui.nocobase.com.
//
// Usage:
//   node scripts/gen-ui-library-catalog.mjs           # write the catalog
//   node scripts/gen-ui-library-catalog.mjs --check   # fail when it is not what the registry would write (CI)
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';

import * as prettier from 'prettier';

const repositoryRoot = path.resolve(
  fileURLToPath(new URL('..', import.meta.url)),
);
const libraryRoot = path.join(repositoryRoot, 'ui-library');
export const catalogFile = path.join(
  repositoryRoot,
  'packages/app/app-skills/skills/nocobase-app-development/references/frontend/references/ui-library.md',
);

const GENERATED =
  '<!-- Generated by scripts/gen-ui-library-catalog.mjs from ui-library/registry. Do not edit: change the item’s registry.json, then run `node scripts/gen-ui-library-catalog.mjs`. -->';

/** Every item the registry index includes, examples among them, in the order the index lists them. */
export async function readRegistry(root = libraryRoot) {
  const index = JSON.parse(
    await readFile(path.join(root, 'registry.json'), 'utf8'),
  );
  const items = [];
  for (const include of index.include) {
    const group = JSON.parse(await readFile(path.join(root, include), 'utf8'));
    items.push(...group.items);
  }
  return items;
}

const kindOf = (item) =>
  item.type === 'registry:block' ? 'block' : 'component';

/** Where `shadcn add` writes the item: a block's own directory, or each of a component's files. */
function locationOf(item) {
  if (item.type === 'registry:block')
    return `\`client/extensions/nocobase-${item.name}/\``;
  return item.files.map((file) => `\`${file.target}\``).join(', ');
}

const pluginsOf = (item) =>
  (item.dependencies ?? [])
    .map((dependency) => dependency.slice(0, dependency.lastIndexOf('@')))
    .filter((name) => name.startsWith('@nocobase/app-plugin-'));

const itemsOf = (item) =>
  (item.registryDependencies ?? []).filter((name) =>
    name.startsWith('@nocobase/'),
  );

export function itemSection(item, examples) {
  const example = examples.find(
    (candidate) => candidate.name === `${item.name}-demo`,
  );
  const plugins = pluginsOf(item);
  const lines = [
    `### ${item.name}`,
    '',
    item.description,
    '',
    `- Kind: ${kindOf(item)}`,
    `- Install: \`yes n | pnpm exec shadcn add @nocobase/${item.name}\``,
    `- Installs to: ${locationOf(item)}`,
    `- Plugin dependencies: ${plugins.length ? plugins.map((name) => `\`${name}\``).join(', ') : 'none'}`,
  ];
  const items = itemsOf(item);
  if (items.length)
    lines.push(
      `- Also installs: ${items.map((name) => `\`${name}\``).join(', ')}`,
    );
  if (example)
    lines.push(
      `- Example: \`@nocobase/${example.name}\` (\`pnpm exec shadcn view @nocobase/${example.name}\`)`,
    );
  if (item.docs) lines.push(`- After installing: ${item.docs}`);
  return `${lines.join('\n')}\n`;
}

export function renderCatalog(items) {
  const installable = items.filter((item) => item.type !== 'registry:example');
  const examples = items.filter((item) => item.type === 'registry:example');
  const groups = new Map();
  for (const item of installable) {
    const group = item.meta?.group ?? 'Other';
    groups.set(group, [...(groups.get(group) ?? []), item]);
  }
  const sections = [...groups.entries()]
    .sort(([a], [b]) => a.localeCompare(b))
    .map(
      ([group, list]) =>
        `## ${group}\n\n${list.map((item) => itemSection(item, examples)).join('\n')}`,
    );
  return [
    '# NocoBase UI Library catalog',
    '',
    GENERATED,
    '',
    'Every item of the `@nocobase` shadcn registry (the NocoBase UI Library, previewed at https://ui.nocobase.com), as of this release of the Skill. A component installs into `client/components/` and a block into `client/extensions/nocobase-<item>/`; every item has a usage example, `@nocobase/<item>-demo`, to read before using it. Look an item up live first, as [section 3 of `styling.md`](styling.md#3-use-shadcn) says, and use this list when the registry cannot be reached.',
    '',
    ...sections,
  ].join('\n');
}

async function format(content) {
  const options = (await prettier.resolveConfig(catalogFile)) ?? {};
  return prettier.format(content, { ...options, filepath: catalogFile });
}

async function main(argv) {
  const check = argv.includes('--check');
  const content = await format(renderCatalog(await readRegistry()));
  const relative = path.relative(repositoryRoot, catalogFile);
  if (check) {
    const current = await readFile(catalogFile, 'utf8').catch(() => undefined);
    if (current === content) {
      console.log(`The UI Library catalog is up to date (${relative}).`);
      return 0;
    }
    console.error(
      `${relative} is not what ui-library/registry gives.\nRun \`node scripts/gen-ui-library-catalog.mjs\` and commit the result.`,
    );
    return 1;
  }
  await writeFile(catalogFile, content);
  console.log(`Wrote ${relative}.`);
  return 0;
}

if (
  process.argv[1] &&
  path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  process.exitCode = await main(process.argv.slice(2));
}
